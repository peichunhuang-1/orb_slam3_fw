#!/usr/bin/env python3
"""Generates the fully unrolled hot-path shaders: blur, fast and harris.

Why generated: on the Raspberry Pi 5 (V3D, Mesa v3dv) a private or constant array indexed
with a run-time index is spilled to scratch memory, which made the first versions 8-13x
slower. Every index here is resolved at generation time, so the shaders contain scalar
variables only.

Register pressure and loads are the next limits on V3D (V3D_DEBUG=shaderdb on a Pi 5): up
to ~32 live values a QPU runs 4 threads, up to ~64 it runs 2, beyond that it spills. The
shapes below were chosen by measuring alternatives on a Pi 5 at 512x512 (GPU ms):
  blur   : 4x4 block 5.84, 4x2 6.13, 4x1 7.52, 4x2 with 16-bit lanes 5.64 (used)
  fast   : 1 pixel/thread 6.54 (4 threads, but not faster), 4 pixels/thread sharing word
           loads 6.20, 4 pixels/thread with a packed compass pre-test 5.58 (used)
  harris : 9x9 bytes up front 5.52, rows loaded late 5.48 (compiler hoists the loads anyway),
           word loads + column sums 2.19 (used)

The generated files are committed, so building does not need Python. Re-run this script
only after changing it:  python3 tools/gen_shaders.py
"""
import os

GAUSS7 = [18, 34, 49, 54, 49, 34, 18]  # 7-tap Gaussian (sigma ~2), sums to 256
# FAST circle of radius 3 as (dx, dy), in the same order as OpenCV
CIRCLE = [(0, 3), (1, 3), (2, 2), (3, 1), (3, 0), (3, -1), (2, -2), (1, -3),
          (0, -3), (-1, -3), (-2, -2), (-3, -1), (-3, 0), (-3, 1), (-2, 2), (-1, 3)]
OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "shaders")
HEADER = """#version 450
#extension GL_GOOGLE_include_directive : require
// Generated by tools/gen_shaders.py - do not edit by hand."""

# Workgroup tile in pixels = local size x pixels per thread (blur 16x8 x 4x2, fast 16x8 x 4x1);
# kBlurTile* / kFastTile* in src/orb_vk.cpp must agree.


def write(name, lines):
    with open(os.path.join(OUT_DIR, name + ".comp"), "w") as f:
        f.write("\n".join(lines) + "\n")


def start(local, desc):
    L = [HEADER, f"layout(local_size_x = {local[0]}, local_size_y = {local[1]}) in;", '#include "common.glsl"', ""]
    L += ["// " + d for d in desc]
    L.append("")
    return L


LEVEL = "    int W = pc.w, H = pc.h, OFF = pc.off, STR = pc.stride;   // current level (per-level dispatch)"


def pack4(a):
    return (f"(({a}0 + 32768u) >> 16) | ((({a}1 + 32768u) >> 16) << 8) | "
            f"((({a}2 + 32768u) >> 16) << 16) | ((({a}3 + 32768u) >> 16) << 24)")


def gauss_sum(prefix, j):
    return " + ".join(f"{GAUSS7[k]}u * {prefix}{k + j}" for k in range(7))


# ---------------------------------------------------------------------------------------------
# Blur
# ---------------------------------------------------------------------------------------------
# Two pixels per uint: lanes (p_k, p_k+2) in bits 0-15 / 16-31. A lane sum is at most
# 256 * 255 = 65280, so the 7-tap horizontal sums of two pixels never carry into each other.
HROW_SWAR = """// Horizontal 7-tap filter of one input row for the 4 output columns x4 .. x4+3, computed on
// two 16-bit lanes per uint: h02 = h0 | h2 << 16 and h13 = h1 | h3 << 16 (sums <= 65280).
// Columns x4-4 .. x4+7 are three aligned words; at the row ends they include the row padding,
// which repeats the edge pixels (clamp to edge), so no block needs special handling.
void hrow2(int row, int x4, out uint h02, out uint h13) {
    int wi = (row + x4) >> 2;
    uint a = pyr[wi - 1], b = pyr[wi], c = pyr[wi + 1];
    const uint M = 0x00FF00FFu;
    uint ea = a & M, oa = (a >> 8) & M;   // (p-1, p1), (p0, p2)
    uint eb = b & M, ob = (b >> 8) & M;   // (p3, p5), (p4, p6)
    uint ec = c & M, oc = (c >> 8) & M;   // (p7, p9), (p8, p10)
    // q<k> = p_k | p_k+2 << 16, with p0 = column x4-3
    uint q0 = oa, q1 = (ea >> 16) | (eb << 16), q2 = (oa >> 16) | (ob << 16), q3 = eb;
    uint q4 = ob, q5 = (eb >> 16) | (ec << 16), q6 = (ob >> 16) | (oc << 16), q7 = ec;
    h02 = """ + " + ".join(f"{GAUSS7[k]}u * q{k}" for k in range(7)) + """;
    h13 = """ + " + ".join(f"{GAUSS7[k]}u * q{k + 1}" for k in range(7)) + """;
}
"""


def gen_blur(rows=2):
    """Separable 7x7 Gaussian, horizontal and vertical in one pass, 4 x `rows` pixels per thread.

    Each input row is filtered horizontally once (on two 16-bit lanes per uint) and
    accumulated into every output row it contributes to. The left / right image border comes
    from the row padding of the pyramid (edge pixels repeated), so there is a single code path:
    a separate border path in the same kernel tripled its instruction count and made it spill
    on V3D (frame 17.1 -> 13.9 ms without it, 600x400 on a Pi 5).
    """
    L = start((16, 8), [
        "7x7 separable Gaussian (weights sum to 256), horizontal and vertical in one pass.",
        f"Each thread writes a 4 x {rows} pixel block: it filters each of the {rows + 6} input rows",
        "horizontally once, on two 16-bit lanes per uint, and accumulates it into every output",
        "row it contributes to. Rows are clamped; columns outside the image come from the row",
        "padding, which repeats the edge pixels."])
    L.append(HROW_SWAR)
    L.append("void main() {")
    L.append(LEVEL)
    L.append("    int x4 = int(gl_GlobalInvocationID.x) * 4;")
    L.append(f"    int y0 = int(gl_GlobalInvocationID.y) * {rows};")
    L.append("    if (x4 >= W || y0 >= H) return;")
    L.append("    int ymax = H - 1;")
    for o in range(rows):
        L.append(f"    uint a{o}_0 = 0u, a{o}_1 = 0u, a{o}_2 = 0u, a{o}_3 = 0u;  // output row y0+{o}")
    L.append("    uint h02, h13;")
    for i in range(rows + 6):
        L.append(f"    hrow2(OFF + clamp(y0 + ({i - 3}), 0, ymax) * STR, x4, h02, h13);")
        for o in range(rows):
            k = i - o
            if 0 <= k <= 6:
                g = GAUSS7[k]
                L.append(f"    a{o}_0 += {g}u * (h02 & 0xFFFFu); a{o}_2 += {g}u * (h02 >> 16); "
                         f"a{o}_1 += {g}u * (h13 & 0xFFFFu); a{o}_3 += {g}u * (h13 >> 16);")
    L.append("    int dst = (OFF + y0 * STR + x4) >> 2, ws = STR >> 2;")
    for o in range(rows):
        guard = "" if o == 0 else f"if (y0 + {o} < H) "
        L.append(f"    {guard}blurImg[dst + {o} * ws] = {pack4(f'a{o}_')};")
    L.append("}")
    write("blur", L)


# ---------------------------------------------------------------------------------------------
# FAST
# ---------------------------------------------------------------------------------------------
FAST_FUNCS = """// true if the 16-bit mask m contains 9 contiguous set bits (circularly)
bool has9(uint m) {
    uint m32 = m | (m << 16);
    uint r = m32;
    for (int k = 1; k < 9; ++k) r &= (m32 >> k);
    return (r & 0xFFFFu) != 0u;
}
// true if two circularly adjacent bits of the 4-bit compass mask q are set
bool adjPair(uint q) {
    uint r = q & ((q >> 1) | (q << 3));
    return (r & 0xFu) != 0u;
}
void emitCorner(int x, int y, int l) {
    uint idx = atomicAdd(cornerCount, 1u);
    if (idx < uint(pc.maxCorners)) corners[idx] = uint(x) | (uint(y) << 13) | (uint(l) << 26);
    else atomicMax(cornerOverflow, 1u);
}
"""


COMPASS2 = """// Packed compass test for 2 pixels (16-bit lanes): bit 15 / bit 31 set if the pixel passes.
uint compass2(uint c, uint b, uint r, uint t, uint l, uint t1) {
    const uint HI = 0x80008000u;
    uint ct = c + t1;
    uint bb = ((b | HI) - ct) & HI, br = ((r | HI) - ct) & HI;   // brighter than c + thr
    uint bt = ((t | HI) - ct) & HI, bl = ((l | HI) - ct) & HI;
    uint ch = c | HI;
    uint db = (ch - (b + t1)) & HI, dr = (ch - (r + t1)) & HI;    // darker than c - thr
    uint dt = (ch - (t + t1)) & HI, dl = (ch - (l + t1)) & HI;
    // compass order bottom, right, top, left: a 9-arc covers two adjacent ones
    return (bb & br) | (br & bt) | (bt & bl) | (bl & bb) | (db & dr) | (dr & dt) | (dt & dl) | (dl & db);
}
"""

# Per-cell thresholds (pc.fastLo > 0) run FAST twice: pass 1 at pc.fastThr exactly as without
# them, then fast_mark.comp marks the cells that got a corner, cell_list.comp lists the others,
# fast_cells.comp runs the pre-test at pc.fastLo over the listed cells only, and fast_full.comp
# runs again with pc.fastPass2 = 1 on those blocks (fastCand[] from index maxCorners, counter
# fastCand2Count), appending to corners[]. Textured cells cost nothing extra.
FAST_PASS = """    bool p2 = pc.fastPass2 != 0;
"""


def gen_fast():
    """FAST-9 pre-test for 4 adjacent pixels per thread (per level); passing blocks are listed.

    The 4 compass points of all 4 pixels come from 5 aligned loads: rows y-3 and y+3 (one
    uint each, same columns) and row y (three uints, for the centre and the +-3 columns).
    The bright / dark comparisons run on two 16-bit lanes per uint:
        v > c + t  <=>  bit 15 of ((v | 0x8000) - (c + t + 1))
        v < c - t  <=>  bit 15 of ((c | 0x8000) - (v + t + 1))
    Lanes stay in 0x7E01 .. 0x80FF, so nothing borrows across lanes. Blocks with a passing
    pixel are appended to fastCand[]; fast_full.comp runs the full test on that list. Running
    the full test here instead made every SIMD group take the slow path as soon as one of its
    64 pixels passed.
    """
    L = start((16, 8), [
        "FAST-9 pre-test for 4 horizontally adjacent pixels per thread: 5 aligned loads decide",
        "for all 4 pixels whether two adjacent compass points are both brighter or both darker.",
        "Blocks with a passing pixel go to fastCand[] for the full test (fast_full.comp).",
        "Requires border >= 11."])
    L.append(COMPASS2)
    L.append("void main() {")
    L.append(LEVEL)
    L.append("    int x4 = int(gl_GlobalInvocationID.x) * 4;")
    L.append("    int y  = int(gl_GlobalInvocationID.y);")
    L.append("    if (y < pc.border || y >= H - pc.border) return;")
    L.append("    if (x4 + 3 < pc.border || x4 >= W - pc.border) return;")
    L.append("    int ws = STR >> 2, wy = (OFF + y * STR + x4) >> 2;   // uint holding columns x4 .. x4+3 of row y")
    L.append("    uint w3_0 = pyr[wy - 1], w3_1 = pyr[wy], w3_2 = pyr[wy + 1];  // row y, columns x4-4 .. x4+7")
    L.append("    uint w0_1 = pyr[wy - 3 * ws], w6_1 = pyr[wy + 3 * ws];        // rows y-3 / y+3, columns x4 .. x4+3")
    L.append("    uint rgt = (w3_1 >> 24) | (w3_2 << 8);   // column +3 of each pixel")
    L.append("    uint lft = (w3_0 >> 8) | (w3_1 << 24);   // column -3 of each pixel")
    L.append("    const uint M = 0x00FF00FFu;")
    L.append("    uint t1 = uint(pc.fastThr + 1) * 0x00010001u;")
    L.append("    uint pe = compass2(w3_1 & M, w6_1 & M, rgt & M, w0_1 & M, lft & M, t1);                  // pixels 0, 2")
    L.append("    uint po = compass2((w3_1 >> 8) & M, (w6_1 >> 8) & M, (rgt >> 8) & M, (w0_1 >> 8) & M, (lft >> 8) & M, t1);  // 1, 3")
    L.append("    uint pass = ((pe >> 15) & 1u) | ((po >> 14) & 2u) | ((pe >> 29) & 4u) | ((po >> 28) & 8u);  // bit j: pixel x4+j")
    L.append("    int lo = pc.border - x4, hi = W - pc.border - x4;   // pixels j in [lo, hi) are inside the border")
    L.append("    pass &= (lo <= 0 ? 15u : (15u << lo) & 15u) & (hi >= 4 ? 15u : (1u << hi) - 1u);")
    L.append("    if (pass == 0u) return;")
    L.append("    uint i = atomicAdd(fastCandCount, 1u);")
    L.append("    if (i < uint(pc.maxCorners)) fastCand[i] = uint(x4 >> 2) | (uint(y) << 11) | (uint(SC_LEVEL_OR_PC) << 24) | (pass << 28);")
    L.append("    else atomicMax(cornerOverflow, 1u);")
    L.append("}")
    write("fast", [x.replace("SC_LEVEL_OR_PC", "pc.level") for x in L])


def gen_fast_full():
    """Full FAST-9 test for the blocks listed by fast.comp, all levels in one grid-stride pass."""
    L = start((64, 1), [
        "Full FAST-9 test (16-pixel circle, 9 contiguous) for the blocks listed by fast.comp:",
        "x4 / 4 | y << 11 | level << 24 | pass mask << 28. Loads the 7 x 3 word window and tests",
        "the pixels of the mask; corners are appended to corners[].",
        "Each workgroup takes a contiguous part of the list, so corners keep the list's level and",
        "raster order (a grid-stride loop mixed them, which made describe.comp 20% slower).",
        "Pass 2 of the per-cell thresholds (pc.fastPass2): the blocks after maxCorners, at pc.fastLo."])
    L.append(FAST_FUNCS)
    L.append("void main() {")
    L.append(FAST_PASS)
    L.append("  if (p2 && aborted()) return;   // abnormal frame after pass 1 (common.glsl)")
    L.append("  int thr = p2 ? pc.fastLo : pc.fastThr;")
    L.append("  uint base = p2 ? uint(pc.maxCorners) : 0u;")
    L.append("  uint n = min(p2 ? fastCand2Count : fastCandCount, uint(pc.maxCorners));")
    L.append("  uint per = (n + gl_NumWorkGroups.x - 1u) / gl_NumWorkGroups.x;")
    L.append("  uint end = min((gl_WorkGroupID.x + 1u) * per, n);")
    L.append("  for (uint e_ = gl_WorkGroupID.x * per + gl_LocalInvocationID.x; e_ < end; e_ += gl_WorkGroupSize.x) {")
    L.append("    // abnormal frame (common.glsl): stop as soon as the corner count passes the limit. Costs")
    L.append("    // ~0.3 ms per normal 720x540 frame, saves ~8 ms per abnormal one (checking every 8th block")
    L.append("    // was not cheaper).")
    L.append("    if (pc.abortCorners > 0 && cornerCount > uint(pc.abortCorners)) break;")
    L.append("    uint e = fastCand[base + e_];")
    L.append("    int x4 = int(e & 0x7FFu) * 4, y = int((e >> 11) & 0x1FFFu), l = int((e >> 24) & 15u);")
    L.append("    uint pass = e >> 28;")
    L.append("    ivec4 Lv = consts[LEVEL_BASE + l];")
    L.append("    int ws = Lv.w >> 2, wb = ((Lv.z + y * Lv.w + x4) >> 2) - 3 * ws - 1;")
    L.append("    // w<r>_<k> = row y-3+r, uint k from column x4-4")
    for r in range(7):
        L.append("    " + " ".join(f"uint w{r}_{k} = pyr[wb + {r} * ws + {k}];" for k in range(3)))

    def pix(r, col):
        b = col + 4
        return f"int((w{r}_{b >> 2} >> {(b & 3) * 8}u) & 255u)"
    for j in range(4):
        L.append(f"    if ((pass & {1 << j}u) != 0u) {{  // pixel x4+{j}")
        L.append(f"        int c_ = {pix(3, j)};")
        L.append("        int hi = c_ + thr, lo = c_ - thr;")
        for i, (dx, dy) in enumerate(CIRCLE):
            L.append(f"        int v{i} = {pix(3 + dy, j + dx)};")
        L.append("        uint bright = " + " | ".join(f"(uint(v{i} > hi) << {i})" for i in range(16)) + ";")
        L.append("        uint dark = " + " | ".join(f"(uint(v{i} < lo) << {i})" for i in range(16)) + ";")
        L.append(f"        if (has9(bright) || has9(dark)) emitCorner(x4 + {j}, y, l);")
        L.append("    }")
    L.append("  }")
    L.append("}")
    write("fast_full", L)


# ---------------------------------------------------------------------------------------------
# Harris
# ---------------------------------------------------------------------------------------------
HARRIS_HEAD = [
    "void main() {",
    "  if (aborted()) return;   // abnormal frame (common.glsl)",
    "  uint n = min(cornerCount, uint(pc.maxCorners));",
    "  for (uint i = gl_GlobalInvocationID.x; i < n; i += gridStride()) {  // grid-stride over corners",
    "    uint e = corners[i];",
    "    int x = int(e & 0x1FFFu), y = int((e >> 13) & 0x1FFFu), l = int(e >> 26);",
    "    ivec4 Lv = consts[LEVEL_BASE + l];",
    "    int stride = Lv.w;",
    "    int base = Lv.z + (y - 4) * stride + (x - 4);   // top-left of the 9x9 window",
    "    int a = 0, b = 0, cc = 0, ix, iy;",
]
HARRIS_TAIL = [
    "    // `precise` forbids FMA contraction so results match the CPU reference",
    "    precise float fa = float(a), fb = float(b), fc = float(cc);",
    "    precise float tr = fa + fb;",
    "    precise float rr = (fa * fb - fc * fc - pc.harrisK * tr * tr) * pc.harrisScale4;",
    "    score[Lv.z + y * stride + x] = rr > 0.0 ? rr : 0.0;",
    "  }",
    "}",
]


def gen_harris():
    L = start((64, 1), [
        "Harris response (3x3 Sobel, 7x7 window) for each FAST corner, grid-stride loop.",
        "Each window row is three uint loads, realigned once (all rows share the same byte",
        "offset). Per output row r, with V(c) = P[r-1][c] + 2 P[r][c] + P[r+1][c] and",
        "D(c) = P[r+1][c] - P[r-1][c]:  ix(c) = V(c+1) - V(c-1),  iy(c) = D(c-1) + 2 D(c) + D(c+1).",
        "Columns are processed left to right so only a few V and D values are live."])
    L += HARRIS_HEAD
    L.append("    int sh = (base & 3) * 8;            // same byte offset for every row of the window")
    L.append("    int wi0 = base >> 2, ws = stride >> 2;")
    L.append("    bool aligned = sh == 0;")

    def load(r):  # aligned words r<r>_0 (cols 0-3), r<r>_1 (cols 4-7), r<r>_2 (col 8 in bits 0-7)
        L.append(f"    uint u{r}_0 = pyr[wi0 + {r} * ws], u{r}_1 = pyr[wi0 + {r} * ws + 1], u{r}_2 = pyr[wi0 + {r} * ws + 2];")
        L.append(f"    uint r{r}_0 = aligned ? u{r}_0 : (u{r}_0 >> sh) | (u{r}_1 << (32 - sh));")
        L.append(f"    uint r{r}_1 = aligned ? u{r}_1 : (u{r}_1 >> sh) | (u{r}_2 << (32 - sh));")
        L.append(f"    uint r{r}_2 = u{r}_2 >> sh;")

    def px(r, c):
        return f"int((r{r}_{c >> 2} >> {(c & 3) * 8}u) & 255u)"
    load(0)
    load(1)
    for r in range(1, 8):
        load(r + 1)
        L.append("    {")  # own scope per output row: v<c> / d<c> are re-declared
        for c in range(9):
            L.append(f"    int v{c} = {px(r-1, c)} + 2 * {px(r, c)} + {px(r+1, c)}, d{c} = {px(r+1, c)} - {px(r-1, c)};")
            if c >= 2:
                L.append(f"    ix = v{c} - v{c-2}; iy = d{c-2} + 2 * d{c-1} + d{c};")
                L.append("    a += ix * ix; b += iy * iy; cc += ix * iy;")
        L.append("    }")
    L += HARRIS_TAIL
    write("harris", L)


if __name__ == "__main__":
    gen_blur(rows=2)
    gen_fast()
    gen_fast_full()
    gen_harris()
    print("generated blur, fast, fast_full, harris in", os.path.normpath(OUT_DIR))
